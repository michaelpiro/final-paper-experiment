"""tsp_repro.tables — emit the tables/*.tex files the TSP paper \\input's.

Score archives are self-contained (scores + labels per cell), so every metric
here is computed from disk; no model is ever needed.

Filename convention (runner.py): double-underscore separated,
    scores__{scene}__{sig}__{det}__seed{k}__{model}__{theta}.npz
    train__{scene}__{sig}__{det}__seed{k}.npz
The old colab-deep archive (scores_{det}_seed{k}_{model}_{theta}.npz) is also
parsed, tagged as scene=pavia4, sig=bitumen.
"""

import os
import re
from collections import defaultdict

import numpy as np
from scipy.stats import norm as _norm

import tsp_repro  # noqa: F401
from src.metrics import dr_at_fpr, partial_auc

_NEW = re.compile(r"scores__(?P<scene>[^_]+)__(?P<sig>.+?)__(?P<det>.+?)"
                  r"__seed(?P<seed>\d+)__(?P<model>\w+)__(?P<theta>[\d.]+)\.npz")
_OLD = re.compile(r"scores_(?P<det>[A-Za-z-]+)_seed(?P<seed>\d+)"
                  r"_(?P<model>\w+)_(?P<theta>[\d.]+)\.npz")


def collect(dirs):
    """{(scene, sig, det, model, theta): {seed: path}}"""
    cells = defaultdict(dict)
    for d in dirs:
        for fn in sorted(os.listdir(d)):
            m = _NEW.match(fn)
            if m:
                g = m.groupdict()
                scene, sig = g["scene"], g["sig"]
            else:
                m = _OLD.match(fn)
                if not m:
                    continue
                g = m.groupdict()
                scene, sig = "pavia4", "bitumen"
            key = (scene, sig, g["det"], g["model"], float(g["theta"]))
            cells[key].setdefault(int(g["seed"]), os.path.join(d, fn))
    return cells


# --------------------------------------------------------------------------
# Per-cell metrics
# --------------------------------------------------------------------------
def cell_metrics(path, alpha=0.05, train_scores=None):
    """AUC, pAUC, Pd@alpha, and detection/false-alarm at the analytic
    (z-quantile) and empirical (train-quantile) CFAR thresholds."""
    d = np.load(path)
    s, y = d["scores"].astype(np.float64), d["labels"]
    from sklearn.metrics import roc_auc_score
    out = dict(auc=roc_auc_score(y, s),
               pauc=partial_auc(y, s, fpr_max=alpha),
               pd_at_fa=dr_at_fpr(y, s, fpr=alpha))
    thr_an = _norm.ppf(1 - alpha)
    out["pd_analytic"] = float((s[y == 1] > thr_an).mean())
    out["pfa_analytic"] = float((s[y == 0] > thr_an).mean())
    if train_scores is not None:
        thr_emp = float(np.quantile(train_scores, 1 - alpha))
        out["pd_empirical"] = float((s[y == 1] > thr_emp).mean())
        out["pfa_empirical"] = float((s[y == 0] > thr_emp).mean())
    return out


def _mean_std(vals):
    return f"{np.mean(vals):.3f}$\\pm${np.std(vals):.3f}"


# --------------------------------------------------------------------------
# Tables
# --------------------------------------------------------------------------
def auc_table(cells, scene, sig, dets, thetas, caption, label,
              model="additive", bold_best=True):
    """Booktabs AUC table: detectors x thetas, mean+-std over seeds."""
    rows, values = [], {}
    for det in dets:
        vals_per_theta = []
        for th in thetas:
            key = (scene, sig, det, model, th)
            paths = cells.get(key, {})
            aucs = []
            for seed, p in sorted(paths.items()):
                d = np.load(p)
                from sklearn.metrics import roc_auc_score
                aucs.append(roc_auc_score(d["labels"], d["scores"]))
            vals_per_theta.append(aucs)
        values[det] = vals_per_theta
    best = {}
    if bold_best:
        for j, _ in enumerate(thetas):
            means = {d: np.mean(values[d][j]) for d in dets if values[d][j]}
            if means:
                best[j] = max(means, key=means.get)
    for det in dets:
        entries = []
        for j, vals in enumerate(values[det]):
            if not vals:
                entries.append("--")
                continue
            e = _mean_std(vals)
            if best.get(j) == det:
                e = f"\\textbf{{{e}}}"
            entries.append(e)
        rows.append(f"{det} & " + " & ".join(entries) + " \\\\")
    head = " & ".join(f"$\\theta={th}$" for th in thetas)
    return "\n".join([
        "% Auto-generated by tsp_repro.tables — do not edit by hand.",
        "\\begin{table}[t]", "\\centering",
        f"\\caption{{{caption}}}", f"\\label{{{label}}}", "\\small",
        "\\begin{tabular}{l" + "c" * len(thetas) + "}", "\\toprule",
        f"Detector & {head} \\\\", "\\midrule",
        *rows,
        "\\bottomrule", "\\end{tabular}", "\\end{table}", ""])


def write_generality_tables(out_dir, dirs, dets, thetas=(0.075, 0.15, 0.225)):
    """Regenerate the six tables/gen_*.tex files (plus deep-baseline rows
    where score archives exist)."""
    cells = collect(dirs)
    spec = [
        ("pavia4", "bitumen", "gen_pavia_bitumen",
         "Pavia University, scene 4 --- bitumen target (paper original). AUC over 5 seeds.",
         "tab:gen-pavia-bitumen"),
        ("pavia4", "metal", "gen_pavia_metal",
         "Pavia University, scene 4 --- metal-sheets target. AUC over 5 seeds.",
         "tab:gen-pavia-metal"),
        ("pavia4", "mix_soil_bricks", "gen_pavia_mix1",
         "Pavia University, scene 4 --- mixed target: mean(bare soil, bricks). AUC over 5 seeds.",
         "tab:gen-pavia-mix1"),
        ("pavia4", "mix_metal_soil", "gen_pavia_mix2",
         "Pavia University, scene 4 --- mixed target: mean(metal sheets, bare soil). AUC over 5 seeds.",
         "tab:gen-pavia-mix2"),
        ("sandiego", "aircraft", "gen_sd1",
         "San Diego I --- real aircraft signature. AUC over 5 seeds.",
         "tab:gen-sd1"),
        ("sandiego2", "aircraft", "gen_sd2",
         "San Diego II --- real aircraft signature. AUC over 5 seeds.",
         "tab:gen-sd2"),
    ]
    os.makedirs(out_dir, exist_ok=True)
    for scene, sig, stem, cap, lab in spec:
        tex = auc_table(cells, scene, sig, dets, list(thetas), cap, lab)
        path = os.path.join(out_dir, stem + ".tex")
        with open(path, "w") as f:
            f.write(tex)
        print("wrote", path)


def cfar_columns_table(cells, scene, sig, dets, theta, train_dir,
                       caption, label, alpha=0.05):
    """Detection + false alarm under the ANALYTIC (z-quantile) and EMPIRICAL
    (train-quantile) CFAR thresholds — the new TSP table columns."""
    rows = []
    for det in dets:
        key = (scene, sig, det, "additive", theta)
        mets = defaultdict(list)
        for seed, p in sorted(cells.get(key, {}).items()):
            tr_p = os.path.join(train_dir,
                                f"train__{scene}__{sig}__{det}__seed{seed}.npz")
            tr = np.load(tr_p)["scores"] if os.path.exists(tr_p) else None
            m = cell_metrics(p, alpha=alpha, train_scores=tr)
            for k, v in m.items():
                mets[k].append(v)
        if not mets:
            continue
        def f(k):
            return _mean_std(mets[k]) if k in mets else "--"
        rows.append(f"{det} & {f('auc')} & {f('pd_analytic')} & "
                    f"{f('pfa_analytic')} & {f('pd_empirical')} & "
                    f"{f('pfa_empirical')} \\\\")
    return "\n".join([
        "% Auto-generated by tsp_repro.tables — do not edit by hand.",
        "\\begin{table}[t]", "\\centering",
        f"\\caption{{{caption}}}", f"\\label{{{label}}}", "\\small",
        "\\begin{tabular}{lccccc}", "\\toprule",
        "Detector & AUC & $P_d^{\\mathrm{an}}$ & $\\hat P_{fa}^{\\mathrm{an}}$"
        " & $P_d^{\\mathrm{emp}}$ & $\\hat P_{fa}^{\\mathrm{emp}}$ \\\\",
        "\\midrule", *rows,
        "\\bottomrule", "\\end{tabular}", "\\end{table}", ""])
